#!/usr/bin/env python3
"""Export this project's tniasm10 source for Glass/SjASMPlus (not a general converter)."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {
    "main": (0, 0, 0), "a1": (1, 0, 0),
    "a2": (0, 1, 0), "enhanced": (1, 0, 1),
}
FLAGS = ("HINOTORI_A1", "HINOTORI_A2", "HINOTORI_ENHANCED")
# Quoted data is kept verbatim; AF' is a register, not a quoted string.
PARTS = re.compile(r'("(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)\'|;.*$)')
TOKEN = re.compile(r"(?<![\w.])[A-Za-z_.][\w.]*")


def split_comment(line: str) -> tuple[str, str]:
    parts = PARTS.split(line)
    for i in range(1, len(parts), 2):
        if parts[i].startswith(";"):
            return "".join(parts[:i]), parts[i]
    return line, ""


class Converter:
    def __init__(self, source: Path, output: Path, target: str, assembler: str):
        self.source = source.resolve()
        self.output = output.resolve()
        if self.output == self.source or self.source.is_relative_to(self.output):
            raise ValueError("Output must not replace the maintained source tree")
        if self.output.is_relative_to(self.source / "asm"):
            raise ValueError("Output must not be inside the maintained asm/ tree")
        self.flags = dict(zip(FLAGS, TARGETS[target]))
        self.assembler = assembler
        self.owner = ""
        self.phase = None
        self.phase_count = 0
        self.seen = set()
        self.local_names = {}

    def local_name(self, name: str) -> str:
        result = name
        if len(name) > 63:
            result = name[:48] + "_" + hashlib.sha256(name.encode()).hexdigest()[:12]
        if result in self.local_names and self.local_names[result] != name:
            raise ValueError(f"Converted local name collision: {name}")
        self.local_names[result] = name
        return result

    def condition(self, expr: str) -> bool:
        match = re.fullmatch(r"(HINOTORI_A1|HINOTORI_A2|HINOTORI_ENHANCED)(?:\s*=\s*(00h|01h))?", expr)
        if not match:
            raise ValueError(f"Unsupported conditional: {expr}")
        value = self.flags[match[1]]
        return bool(value) if match[2] is None else value == int(match[2][:-1], 16)

    def tokens(self, code: str) -> str:
        def replace(match):
            token = match[0]
            if re.fullmatch(r"[A-Fa-f][0-9A-Fa-f]*[hH]", token):
                return "0" + token
            if token.startswith("."):
                if not self.owner:
                    raise ValueError(f"Local symbol without owner: {token}")
                return self.local_name(self.owner + "__LOCAL__" + token[1:])
            if "." in token:
                return self.local_name(token.replace(".", "__LOCAL__"))
            return token
        parts = PARTS.split(code)
        for i in range(0, len(parts), 2):
            parts[i] = TOKEN.sub(replace, parts[i])
        return "".join(parts)

    def end_phase(self) -> str:
        if self.phase is None:
            raise ValueError("DEPHASE without PHASE")
        n = self.phase
        self.phase = None
        if self.assembler == "sjasmplus":
            return "\tENT"
        return f"\tORG\t__HINO_PHYSICAL_{n} + ($ - __HINO_LOGICAL_{n})"

    def file(self, relative: Path):
        path = (self.source / relative).resolve()
        if not path.is_relative_to(self.source / "asm"):
            raise ValueError(f"Include outside asm/: {relative}")
        if path in self.seen:
            raise ValueError(f"Repeated or recursive include: {relative}")
        self.seen.add(path)
        output = ["; Generated by tools/convert.py; edit the maintained tniasm10 source."]
        if relative.as_posix() == "asm/core/assembler.asm":
            output.append("; Native IM instructions replace tniasm10's compatibility macros.")
        else:
            active = True
            stack = []
            for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
                try:
                    code, comment = split_comment(line)
                    stripped = code.strip()
                    directive = re.fullmatch(r"%?(IF|ELSE|ENDIF)\b\s*(.*)", stripped, re.IGNORECASE)
                    if directive:
                        op, expr = directive.groups()
                        op = op.upper()
                        if op == "IF":
                            condition = self.condition(expr)
                            stack.append((active, condition, False))
                            active = active and condition
                        elif op == "ELSE":
                            parent, condition, seen_else = stack[-1]
                            if seen_else or expr:
                                raise ValueError("Invalid ELSE")
                            stack[-1] = (parent, condition, True)
                            active = parent and not condition
                        else:
                            if expr:
                                raise ValueError("Invalid ENDIF")
                            active = stack.pop()[0]
                        if comment:
                            output.append(comment)
                        continue
                    if not active:
                        continue
                    include = re.fullmatch(r'INCLUDE\s+"([^"]+)"', stripped)
                    if include:
                        self.file(Path(include[1]))
                        output.append(line)
                        continue
                    label = re.match(r"^([A-Za-z_][\w]*):", code)
                    if label:
                        self.owner = label[1]
                    code = self.tokens(code)
                    stripped = code.strip()
                    if stripped.startswith("PHASE\t") or stripped.startswith("PHASE "):
                        expr = stripped.split(None, 1)[1]
                        if self.phase is not None:
                            output.append(self.end_phase())
                        self.phase_count += 1
                        self.phase = self.phase_count
                        n = self.phase
                        if self.assembler == "sjasmplus":
                            output.append(f"\tDISP\t{expr}\t{comment}")
                        else:
                            output.extend((f"__HINO_PHYSICAL_{n}: EQU $",
                                           f"__HINO_LOGICAL_{n}: EQU {expr}",
                                           f"\tORG\t__HINO_LOGICAL_{n}\t{comment}"))
                    elif stripped == "DEPHASE":
                        output.append(self.end_phase() + "\t" + comment)
                    elif self.assembler == "sjasmplus" and re.match(r"DS\s", stripped):
                        # Zero-length padding is valid in tniasm10; SjASMPlus warns
                        # about its unused fill byte. Keep the same emitted bytes.
                        count = stripped.split(None, 1)[1].split(",", 1)[0]
                        output.extend((f"\tIF\t({count}) != 00h", code + comment, "\tENDIF"))
                    elif stripped.startswith("%"):
                        raise ValueError("Unsupported tniasm10 directive")
                    else:
                        output.append(code + comment)
                except (ValueError, IndexError) as exc:
                    raise ValueError(f"{relative}:{number}: {exc}") from exc
            if stack:
                raise ValueError(f"Unclosed conditional in {relative}")
        destination = self.output / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text("\n".join(output) + "\n", encoding="utf-8", newline="\n")


def export(source: Path, output: Path, target: str, assembler: str) -> Path:
    if assembler not in ("glass", "sjasmplus"):
        raise ValueError(f"Unsupported assembler: {assembler}")
    converter = Converter(source, output, target, assembler)
    entry = Path("asm") / f"hinotori-{target}.asm"
    converter.file(entry)
    if converter.phase is not None:
        raise ValueError("Unclosed PHASE")
    return output / entry


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assembler", choices=("glass", "sjasmplus"), required=True)
    parser.add_argument("--target", choices=(*TARGETS, "all"), default="all")
    parser.add_argument("--output", type=Path, help="Export directory (one subdirectory per target)")
    args = parser.parse_args()
    output = (args.output or ROOT / "build" / "generated" / args.assembler).resolve()
    for target in TARGETS if args.target == "all" else (args.target,):
        entry = export(ROOT, output / target, target, args.assembler)
        print(entry)


if __name__ == "__main__":
    main()
