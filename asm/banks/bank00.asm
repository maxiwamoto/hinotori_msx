	LD	(SUBSCREEN_ACTIVE_MODE),A
	CALL	BLANK_DISPLAY_AND_CLEAR_ALL_SPRITES
	CALL	QUEUE_LEVEL_OR_ATTRACT_BGM
	JR	LOAD_STAGE_FONTS_TILESETS_AND_PALETTES
	IF	HINOTORI_ENHANCED = 00h

; Unreferenced stage-blank helper (0 callers in ROM)
PREPARE_STAGE_GRAPHICS_AND_OBJECTS:
	CALL	SET_DEFAULT_UPWARD_SCROLL_DELTA
	JP	BLANK_DISPLAY_AND_CLEAR_ALL_SPRITES
	ENDIF

; Full stage-start setup from Stage Intro or Attract Demo: reset transient items, load all
; graphics, map, Gao, and objects
INITIALIZE_NEW_STAGE_ENTRY_SETUP:
	LD	A,01h
	LD	(SUBSCREEN_ACTIVE_MODE),A
	CALL	INIT_ENEMY_SPAWN_COUNTERS
	CALL	CLEAR_TRANSIENT_STAGE_BUFF_SLOTS
	CALL	QUEUE_LEVEL_OR_ATTRACT_BGM
	CALL	BLANK_DISPLAY_AND_CLEAR_ALL_SPRITES

; Load alphanumeric & Hiragana UI fonts, shared kanji/stone UI tiles, sprite font, offscreen
; stage VRAM tilesets, and stage/sprite palettes
LOAD_STAGE_FONTS_TILESETS_AND_PALETTES:
	IF	HINOTORI_ENHANCED = 00h
	CALL	LOAD_ALPHANUMERIC_FONT_TO_VRAM
	CALL	LOAD_HIRAGANA_FONT_TO_VRAM
	CALL	LOAD_SHARED_KANJI_AND_STONE_UI_GFX
	ENDIF
	CALL	LOAD_SPRITE_TEXT_FONT_PATTERNS
	CALL	RELOAD_STAGE_VRAM_TILESETS
	IF	HINOTORI_ENHANCED = 00h
	CALL	NOOP_STAGE_ATTR_OVERRIDE_STUB
	ENDIF
	CALL	LOAD_STAGE_AND_SPRITE_PALETTES
	IF	HINOTORI_ENHANCED = 00h
	CALL	NOOP_FONT_SETUP_RET
	ENDIF

; Load route/weapon sprites, clear SAT, decode initial screen map rows, spawn Gao & terrain
; objects, set VDP regs, and enable display
FINALIZE_ROUTE_MAP_OBJECTS_AND_DISPLAY:
	CALL	LOAD_ROUTE_SPRITE_PATTERNS
	CALL	UPLOAD_EQUIPPED_WEAPON_SPRITE_PATTERN
	CALL	CLEAR_CPU_SPRITE_ATTR_TABLE_E0
	IF	HINOTORI_ENHANCED
	CALL	HS_PRE_STAGE_INIT	; asm/enhanced/hscroll_core.asm
	ELSE
	CALL	SET_DEFAULT_UPWARD_SCROLL_DELTA
	ENDIF
	CALL	INITIALIZE_LEVEL_MAP
	CALL	STREAM_INITIAL_SCREEN_TILE_ROWS
	LD	A,(SUBSCREEN_ACTIVE_MODE)
	OR	A
	CALL	NZ,REALIGN_GAO_POSITION_AND_SURFACE_MODE
	CALL	SPAWN_GAO_AND_RESET_WEAPON_SLOTS
	CALL	RESET_STAGE_ENEMY_AND_AUX_STATE
	CALL	INITIALIZE_STAGE_TERRAIN_OBJECTS
	CALL	CONFIGURE_STAGE_VDP_BG_AND_SPRITE_MODE
	IF	HINOTORI_ENHANCED
	CALL	HS_STAGE_INIT	; asm/enhanced/hscroll_core.asm | R#23 + reset horizontal camera
	ELSE
	CALL	WRITE_VERTICAL_SCROLL_REGISTER
	ENDIF
	CALL	ENABLE_VDP_DISPLAY_AND_SPRITES
	LD	A,02h
	LD	(SPAWN_TRAP_GRACE_TIMER),A
	LD	A,24h
	JP	QUEUE_SOUND_COMMAND_IF_UNLOCKED
	IF	HINOTORI_ENHANCED = 00h

; Unreferenced route-reset helper converting 1-based CURRENT_STAGE_DISPLAY_BCD into center route
; (stage - 1) * 3 + 1 and clearing object tables (0 callers in ROM)
CONFIGURE_VDP_SPRITE_AND_SCROLL_REGS:
	LD	A,(CURRENT_STAGE_DISPLAY_BCD)
	DEC	A
	LD	B,A
	ADD	A,A
	ADD	A,B
	INC	A
	LD	(CURRENT_ROUTE_ID),A
	CALL	DERIVE_LEVEL_AND_ROUTE_FROM_ROUTE_ID
	CALL	STORE_LEVEL_ROUTE_TUPLE
	XOR	A
	LD	(CURRENT_STAGE_DISPLAY_BCD),A
	RET
	ENDIF

; Zero temporary per-stage buff counters (INV_TIME_STOP_TIMER, INV_INVISIBILITY_TIMER,
; INV_INVINCIBLE_AURA_TIMER)
CLEAR_TRANSIENT_STAGE_BUFF_SLOTS:
	XOR	A
	LD	(INV_TIME_STOP_TIMER),A
	LD	(INV_INVISIBILITY_TIMER),A
	LD	(INV_INVINCIBLE_AURA_TIMER),A
	RET

; Set V9938 R#8 sprite/VR configuration by LEVEL_INDEX, border color R#7=0Fh, and status
; register R#15=00h
CONFIGURE_STAGE_VDP_BG_AND_SPRITE_MODE:
	LD	A,(LEVEL_INDEX)
	CP	06h
	JR	C,.loc_5daf
	LD	B,28h
	LD	C,08h
	CALL	BIOS_WRTVDP
	JR	.loc_5db6

.loc_5daf:
	LD	B,08h
	LD	C,08h
	CALL	BIOS_WRTVDP

.loc_5db6:
	LD	BC,0F07h
	CALL	BIOS_WRTVDP
	LD	C,0Fh
	LD	DE,0000h
	JP	WRITE_PALETTE_ENTRY_TO_VDP

; Disable VDP display/sprites, clear VRAM and auxiliary SAT blocks, reset display latches,
; and clear dynamic sprite state
BLANK_DISPLAY_AND_CLEAR_ALL_SPRITES:
	CALL	DISABLE_VDP_DISPLAY_AND_SPRITES
	CALL	CLEAR_SPRITES
	CALL	CLEAR_AUXILIARY_VRAM_SAT_E0
	XOR	A
	LD	(DISPLAY_RESET_LATCH),A
	LD	(CALLBACK_SUBTIMER),A
	JP	RESET_AMBIENT_SPAWN_TIMERS_20H	; asm/banks/bank01.asm

; Fill 80h bytes at VRAM_SPRITE_AUX_FILL with Y=E0h to hide all auxiliary SAT entries
CLEAR_AUXILIARY_VRAM_SAT_E0:
	LD	HL,VRAM_SPRITE_AUX_FILL
	LD	BC,0080h
	LD	A,E0h
	JP	FILL_VRAM_BYTES_WITH_A

; Initialize SCROLL_DELTA_ACCUM to FF00h (-1.0 px/step default scroll delta)
SET_DEFAULT_UPWARD_SCROLL_DELTA:
	LD	HL,FF00h
	LD	(SCROLL_DELTA_ACCUM),HL
	RET

; Clear BC+1 bytes starting at (HL) to 00h via LDIR
ZERO_RAM_BLOCK_HL_BC:
	LD	E,L
	LD	D,H
	INC	DE
	LD	(HL),00h
	LDIR
	RET

; Fill 81h bytes of CPU_SPRITE_ATTR_TABLE (E600h) with E0h to hide all staged CPU sprites
CLEAR_CPU_SPRITE_ATTR_TABLE_E0:
	LD	HL,CPU_SPRITE_ATTR_TABLE
	LD	DE,CPU_SAT_CLEAR_DEST
	LD	(HL),E0h
	LD	BC,0080h
	LDIR
	RET

; Scan all MSX primary and expanded subslots for King Kong 2 (type 02h) or other Konami
; RC-series cartridges (type 01h)
DETECT_SUPPORTED_COMPANION_CARTRIDGE:
	LD	BC,0400h
	LD	HL,BIOS_EXPTBL

.loc_5e05:
	PUSH	BC
	PUSH	HL
	LD	A,(HL)
	BIT	07h,A
	JR	NZ,.loc_5e1e
	CALL	TEST_COMPANION_SLOT

.loc_5e0f:
	POP	HL
	POP	BC
	JR	C,.loc_5e1a
	INC	HL
	INC	C
	DJNZ	.loc_5e05
	XOR	A
	IF	HINOTORI_A1 = 00h
	JR	$ + 02h	; Redundant zero-offset jump removed in [a1]
	ENDIF

.loc_5e1a:
	LD	(COMPANION_CART_TYPE),A
	RET

.loc_5e1e:
	CALL	SCAN_EXPANDED_SUBSLOTS
	JR	.loc_5e0f

; Probe all 4 expanded subslots of primary slot C for a supported Konami companion signature
SCAN_EXPANDED_SUBSLOTS:
	AND	80h
	OR	C
	LD	C,A
	LD	B,04h

.loc_5e29:
	PUSH	BC
	CALL	TEST_COMPANION_SLOT
	POP	BC
	RET	C
	LD	A,C
	ADD	A,04h
	LD	C,A
	DJNZ	.loc_5e29
	XOR	A
	RET

; Test candidate slot C for Konami companion signatures at 7FFAh/BFFAh (type 01h) or King
; Kong 2 at 4010h (type 02h)
TEST_COMPANION_SLOT:
	IF	HINOTORI_A1
	LD	A,C	; [a1] Record true candidate slot/subslot ID for King Kong 2
	LD	(KK2_SLOT_ID),A
	ENDIF
	CALL	TEST_OTHER_KONAMI_COMPANION_SIGNATURES
	LD	A,01h
	RET	C
	CALL	TEST_KING_KONG2_SIGNATURE
	LD	A,02h
	RET

; Compare 5 bytes at 4010h in slot C against King Kong 2 signature (43h,44h,07h,45h,FFh)
TEST_KING_KONG2_SIGNATURE:
	LD	DE,KING_KONG2_SIGNATURE_BYTES_4010
	LD	HL,COMPANION_SIG_KK2_ADDR
	LD	B,05h
	JR	COMPARE_BYTES_IN_SLOT

; Check slot C at 7FFAh and BFFAh for supported Konami companion cartridge signatures
TEST_OTHER_KONAMI_COMPANION_SIGNATURES:
	LD	DE,COMPANION_SIGNATURE_BYTES_7FFA
	LD	HL,COMPANION_SIG_PAGE1_END
	LD	B,06h
	CALL	COMPARE_BYTES_IN_SLOT
	RET	C
	LD	DE,COMPANION_SIGNATURE_BYTES_BFFA
	LD	HL,COMPANION_SIG_PAGE2_END
	LD	B,06h

; Read B bytes at HL from slot C via BIOS_RDSLT and compare against (DE); sets Carry on
; match
COMPARE_BYTES_IN_SLOT:
	PUSH	BC
	PUSH	DE
	LD	A,C
	CALL	BIOS_RDSLT
	POP	DE
	POP	BC
	EX	DE,HL
	CP	(HL)
	EX	DE,HL
	JR	NZ,.loc_5e74
	INC	HL
	INC	DE
	DJNZ	COMPARE_BYTES_IN_SLOT
	SCF
	RET

.loc_5e74:
	AND	A
	RET

; 6-byte Konami companion cartridge signature probed at 7FFAh
COMPANION_SIGNATURE_BYTES_7FFA:
	DB	00h,30h,31h,13h,35h,AAh

; 5-byte King Kong 2 header signature probed at 4010h (43h,44h,07h,45h,FFh)
KING_KONG2_SIGNATURE_BYTES_4010:
	DB	43h,44h,07h,45h,FFh

; 6-byte Konami companion cartridge signature probed at BFFAh
COMPANION_SIGNATURE_BYTES_BFFA:
	DB	BAh,B2h,86h,07h,46h,AAh

; Draw and initialize Konami companion-cartridge debug/cheat menu ('MENU / START GAME /
; MODIFY STAGE')
COMPANION_CHEAT_MENU_ENTRY:
