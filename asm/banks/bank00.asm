	CALL	CLEAR_MENU_SUBBAND_AND_DRAW_PROMPT
	LD	HL,CHEAT_STAGE_SELECT_BCD
	LD	DE,B0B8h

; Render 1-byte (2-digit) BCD menu value at (HL) to SCREEN 5 coordinates DE
RENDER_ONE_BCD_MENU_BYTE_AT_DE:
	LD	B,01h
	JP	RENDER_BCD_BYTES_AT_DE

; Positioned 'STAGE NUMBER/' prompt and '01' default string
COMPANION_STAGE_NUMBER_TEXT:
	DB	48h,B8h,"STAGE",00h,"NUMBER/",FFh
	DB	"01",FFh

; Clear menu prompt band and render 'PLAYER NUMBER/' with current BCD lives count at (B8h,
; B8h)
DRAW_COMPANION_PLAYER_LIVES_PROMPT:
	LD	HL,COMPANION_PLAYER_NUMBER_TEXT
	CALL	CLEAR_MENU_SUBBAND_AND_DRAW_PROMPT
	LD	HL,CHEAT_PLAYER_LIVES_BCD
	LD	DE,B8B8h
	JR	RENDER_ONE_BCD_MENU_BYTE_AT_DE

; Clear 184x24 menu prompt sub-band at (24h, B0h) and draw positioned prompt string HL
CLEAR_MENU_SUBBAND_AND_DRAW_PROMPT:
	PUSH	HL
	CALL	CLEAR_COMPANION_PROMPT_SUBBAND
	POP	HL
	JP	DRAW_POSITIONED_TEXT_STRING

; Positioned 'PLAYER NUMBER/' prompt for companion debug menu
COMPANION_PLAYER_NUMBER_TEXT:
	DB	48h,B8h,"PLAYER",00h,"NUMBER/",FFh

; Clear 184x24 pixel sub-band at (X=24h, Y=B0h) in companion debug menu
CLEAR_COMPANION_PROMPT_SUBBAND:
	LD	HL,24B0h
	LD	BC,B818h
	JP	FILL_MENU_VRAM_RECT_WITH_BLACK

; Poll keyboard digits 0..9 via SNSMAT rows 0-1, shift entered digit into BCD work value,
; and redraw value
POLL_NUMERIC_DIGITS_FOR_COMPANION_MENU:
	CALL	POLL_KEYBOARD_DIGIT_ROWS_0_AND_1
	RET	Z
	LD	HL,(CHEAT_MENU_HELD_KEYS)
	LD	D,00h
	LD	B,08h
	LD	A,L
	CALL	FIND_FIRST_PRESSED_KEY_BIT_INDEX
	JR	C,.loc_5f67
	LD	A,H
	LD	B,02h
	CALL	FIND_FIRST_PRESSED_KEY_BIT_INDEX
	RET	NC

.loc_5f67:
	PUSH	DE
	LD	HL,(CHEAT_MENU_VRAM_COORD)
	LD	BC,1008h
	XOR	A
	LD	D,A
	CALL	FILL_VRAM_RECT_HMMV
	POP	DE
	LD	HL,CURRENT_KEY_ROW7_BITS
	LD	(HL),FFh
	LD	HL,CHEAT_MENU_BCD_WORK
	LD	A,D
	RLD
	LD	DE,(CHEAT_MENU_VRAM_COORD)
	LD	B,01h
	CALL	RENDER_BCD_BYTES_AT_DE
	JP	CONVERT_COMPANION_BCD_TO_BINARY_A

; Scan B bits of key mask A rightwards; return Carry=1 and digit index in D on first pressed
; bit
FIND_FIRST_PRESSED_KEY_BIT_INDEX:
	RRA
	RET	C
	INC	D
	DJNZ	FIND_FIRST_PRESSED_KEY_BIT_INDEX
	RET

; Read MSX keyboard matrix rows 0 ('0'-'7') and 1 ('8'-'9') and return newly pressed
; rising-edge bits
POLL_KEYBOARD_DIGIT_ROWS_0_AND_1:
	XOR	A
	CALL	BIOS_SNSMAT
	CPL
	LD	D,A
	LD	A,01h
	CALL	BIOS_SNSMAT
	CPL
	AND	03h
	LD	E,A
	LD	A,D
	LD	HL,CHEAT_MENU_HELD_KEYS
	LD	C,(HL)
	LD	(HL),A
	XOR	C
	AND	(HL)
	LD	D,A
	LD	A,E
	INC	HL
	LD	C,(HL)
	LD	(HL),A
	XOR	C
	AND	(HL)
	LD	E,A
	OR	D
	RET

; Convert 2-digit BCD value in CHEAT_MENU_BCD_WORK into binary integer A (10*hi + lo)
CONVERT_COMPANION_BCD_TO_BINARY_A:
	LD	HL,CHEAT_MENU_BCD_WORK
	LD	A,(HL)
	LD	C,A
	RRCA
	RRCA
	RRCA
	RRCA
	AND	0Fh
	ADD	A,A
	LD	B,A
	ADD	A,A
	ADD	A,A
	ADD	A,B
	LD	B,A
	LD	A,C
	AND	0Fh
	ADD	A,B
	LD	(CHEAT_MENU_DIGIT_BUF),A
	RET

; Poll keyboard matrix row 7 bit 7 (RETURN key) and return NZ on newly pressed rising edge
CHECK_COMPANION_RETURN_KEY_EDGE:
	LD	A,07h
	CALL	BIOS_SNSMAT
	CPL
	AND	80h
	LD	HL,CHEAT_MENU_ROW_KEYS
	LD	C,(HL)
	LD	(HL),A
	XOR	C
	AND	(HL)
	RET

