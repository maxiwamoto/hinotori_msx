	CALL	CHECK_PLAYER_AND_WEAPON_COLLISIONS
	CALL	RUN_PLAYER_WEAPON_AND_ITEM_COLLISIONS
	JP	UPLOAD_ROTATED_SPRITE_ATTRIBUTES

; Build player/weapon hitboxes and run enemy contact, weapon damage, blast-box, pickup, and
; active item checks
RUN_PLAYER_WEAPON_AND_ITEM_COLLISIONS:
	CALL	BUILD_PLAYER_HITBOX_POINTS_ARRAY
	CALL	BUILD_WEAPON_HITBOX_ARRAY
	CALL	TEST_ALL_TERRAIN_OBJECT_HITBOXES
	CALL	TEST_ALL_GAMEPLAY_OBJECT_HITBOXES
	CALL	TEST_AUX_PROJECTILES_HITTING_GAO
	CALL	CHECK_GROUND_ITEM_PICKUPS_BY_GAO
	IF	HINOTORI_ENHANCED
	JP	RETIRE_COLLIDED_WEAPON_SHOTS	; asm/banks/bank01.asm | asm/banks/bank02.asm
	ELSE
	CALL	RETIRE_COLLIDED_WEAPON_SHOTS
	RET

; Disabled developer wall-walk cheat hook (skipped by SCF + CALL NC at 5177h): zeros
; TILE_COLLISION_ATTR_LUT (C900h..C9FFh) so all stage tiles become non-solid
CHECK_GAMEPLAY_SUBSCREEN_HOTKEYS:
	LD	HL,TILE_COLLISION_ATTR_LUT
	LD	DE,TILE_COLLISION_CLEAR_DST
	LD	(HL),00h
	LD	BC,00FFh
	LDIR
	RET
	ENDIF

; Fast intra-level route reload (keeping loaded stage VRAM tilesets & palettes): blank display
; and reload route sprites, map, Gao position, and terrain stream
RELOAD_ROUTE_KEEPING_TILESETS_AND_PALETTE:
	XOR	A
	LD	(SUBSCREEN_ACTIVE_MODE),A
	CALL	BLANK_DISPLAY_AND_CLEAR_ALL_SPRITES
	JR	FINALIZE_ROUTE_MAP_OBJECTS_AND_DISPLAY

; Full cross-level route transition: blank display, queue BGM, and reload fonts, tilesets,
; palettes, sprites, and level map
RELOAD_ROUTE_WITH_FULL_GFX_AND_BGM:
