; CBS v5.2 Format 0 (Compact128) RAM-to-RAM decompressor: HL = source stream, DE = destination buffer
DECOMPRESS_CBS_TO_RAM:
	LD	A,80h
	LD	BC,FFFFh
	PUSH	BC
	CALL	.cbs_get_gamma
	LDIR

.cbs_after_literal:
	ADD	A,A
	JR	NC,.cbs_repeat_offset
	CALL	Z,.cbs_refill_bits
	JR	C,.cbs_new_offset

.cbs_repeat_offset:
	CALL	.cbs_get_gamma
	JR	C,.cbs_copy_match
	ADD	A,A
	JR	NC,.cbs_copy_match
	CALL	Z,.cbs_refill_bits
	JR	C,.cbs_finished

.cbs_copy_match:
	EX	(SP),HL
	PUSH	HL
	ADD	HL,DE
	LDIR
	POP	HL
	EX	(SP),HL

.cbs_after_match:
	ADD	A,A
	JR	NC,.cbs_literal_after_match
	CALL	Z,.cbs_refill_bits
	JR	C,.cbs_new_offset

.cbs_literal_after_match:
	CALL	.cbs_get_gamma
	JR	C,.cbs_copy_literals
	ADD	A,A
	JR	NC,.cbs_copy_literals
	CALL	Z,.cbs_refill_bits
	JR	C,.cbs_finished

.cbs_copy_literals:
	LDIR
	JR	.cbs_after_literal

.cbs_new_offset:
	CALL	.cbs_get_neg_gamma
	INC	BC
	RR	B
	LD	B,C
	LD	C,(HL)
	INC	HL
	RR	B
	RR	C
	EX	(SP),HL
	POP	HL
	PUSH	BC
	CALL	.cbs_get_gamma_first
	INC	BC
	JR	.cbs_copy_match

.cbs_finished:
	POP	BC
	RET

.cbs_refill_bits:
	LD	A,(HL)
	INC	HL
	RLA
	RET

.cbs_get_gamma:
	LD	BC,0001h
	JR	.cbs_gamma_read_control

.cbs_get_neg_gamma:
	LD	BC,FFFEh

.cbs_gamma_read_control:
	ADD	A,A
	JR	NC,.cbs_gamma_loop
	CALL	Z,.cbs_refill_bits
	JR	NC,.cbs_gamma_loop
	CCF
	RET

.cbs_get_gamma_first:
	LD	BC,0001h
	JR	NC,.cbs_gamma_loop
	CCF
	RET

.cbs_gamma_loop:
	ADD	A,A
	CALL	Z,.cbs_refill_bits
	RL	C
	RL	B
	ADD	A,A
	JR	NC,.cbs_gamma_loop
	CALL	Z,.cbs_refill_bits
	JR	NC,.cbs_gamma_loop
	RET

