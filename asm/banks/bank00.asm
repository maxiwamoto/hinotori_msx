; Clear 192x56 pixel companion debug menu body area at (X=20h, Y=98h) to black
CLEAR_COMPANION_MENU_BODY_RECT:
	LD	HL,2098h
	LD	BC,C038h

; Fill SCREEN 5 rectangle (HL=XY, BC=WH) with color 00h via HMMV while preserving HL and
; returning WH in DE
FILL_MENU_VRAM_RECT_WITH_BLACK:
	XOR	A
	LD	D,00h
	PUSH	BC
	PUSH	HL
	CALL	FILL_VRAM_RECT_HMMV
	POP	HL
	POP	DE
	RET
	IF	HINOTORI_ENHANCED = 00h

; Unreferenced helper that clears a menu rectangle and draws a color-0Ch frame (0 callers in ROM)
DRAW_COMPANION_MENU_CURSOR:
	CALL	FILL_MENU_VRAM_RECT_WITH_BLACK
	LD	C,0Ch
