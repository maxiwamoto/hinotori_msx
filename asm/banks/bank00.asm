; Physical Bank 00 (ROM 00000h-01FFFh): Cartridge header, H.TIMI VBlank dispatcher, main state machine, V9938 VDP/VRAM/palette/text/tilemap primitives, Konami mapper & descriptor engine, level streaming, and companion-cartridge detection/menu
; Note: Banks 00-03 form one continuous 32 KiB Core Engine module (PHASE 4000h-BFFFh)
; because an instruction straddles the physical 7FFFh/8000h bank boundary.
	PHASE	4000h

; MSX 'AB' cartridge header (INIT vector at 4002h) and Konami RC-747 companion metadata
; block (4010h-4047h)
CARTRIDGE_ROM_HEADER:
	DB	"AB"	; MSX ROM cartridge signature
	DW	CARTRIDGE_BOOT_INIT	; INIT entry vector
	DW	0000h	; STATEMENT vector (unused)
	DW	0000h	; DEVICE vector (unused)
	DW	0000h	; TEXT vector (unused)
	DB	00h,00h,00h,00h,00h,00h	; Reserved MSX header bytes (400Ah-400Fh)
; Konami RC-747 cartridge identity & companion metadata block (4010h-4047h)
	DB	43h,00h,44h,00h,03h,00h,15h,00h,00h,00h,00h,04h,00h,61h,C1h,00h
	DB	00h,06h,60h,C1h,00h,00h,55h,C1h,F7h,C0h,12h,C0h,32h,C0h,52h,C0h
	DB	13h,C0h,14h,C0h,33h,C0h,34h,C0h,53h,C0h,54h,C0h,49h,9Ch,F2h,C0h
	DB	F4h,C0h,72h,C0h,73h,C0h,74h,C0h

; Primary VBlank interrupt handler installed at BIOS_H_TIMI_ADDR: checks companion mode,
; maps Banks 14/15 to tick sound driver, restores mapper pages, and gates gameplay at half the video refresh rate
; frames
HTIMI_VBLANK_HANDLER:
	DI
	LD	A,(COMPANION_CART_TYPE)
	OR	A
	JP	NZ,HANDLE_COMPANION_PAUSE_COMBO

; Main H.TIMI interrupt body: guard re-entrancy, map sound banks 0Eh/0Fh, tick sound driver,
; and swap SAT buffers
RUN_HTIMI_CORE_IRQ_BODY:
	DI
	LD	HL,IRQ_REENTRY_GUARD
	LD	A,(HL)
	AND	A
	JR	NZ,.loc_40a2
	INC	(HL)
	LD	A,01h
	LD	(MAPPER_PAGE1),A
	LD	A,02h
	LD	(MAPPER_PAGE2),A
	LD	A,03h
	LD	(MAPPER_PAGE3),A
	DI
	LD	A,0Fh
	LD	(MAPPER_PAGE3),A
	LD	A,0Eh
	LD	(MAPPER_PAGE2),A
	CALL	UPDATE_SOUND_ON_INTERRUPT
	DI
	LD	A,(MAPPER_BANK_PAGE3)
	LD	(MAPPER_PAGE3),A
	LD	A,(MAPPER_BANK_PAGE2)
	LD	(MAPPER_PAGE2),A
	LD	A,(MAPPER_BANK_PAGE1)
	LD	(MAPPER_PAGE1),A
	XOR	A
	LD	(IRQ_REENTRY_GUARD),A
	LD	HL,VBLANK_TICK_DIVIDER
	INC	(HL)
	LD	HL,MAIN_FRAME_BUSY
	BIT	00h,(HL)
	JP	NZ,.loc_40a2
	INC	(HL)
	EI
	CALL	RUN_MAIN_STATE_FRAME
	XOR	A
	LD	(MAIN_FRAME_BUSY),A

.loc_40a2:
	EI
	RET

; Unsigned 8-bit offset helper: HL = HL + A
ADD_A_TO_HL:
	ADD	A,L
	LD	L,A
	RET	NC
	INC	H
	RET

; Unsigned 8-bit offset helper: DE = DE + A
ADD_A_TO_DE:
	ADD	A,E
	LD	E,A
	RET	NC
	INC	D
	RET

; Pop caller return address, index inline DW jump table by A, and jump to target handler
INLINE_WORD_DISPATCH:
	POP	HL
	ADD	A,A
	CALL	ADD_A_TO_HL
	LD	E,(HL)
	INC	HL
	LD	D,(HL)
	EX	DE,HL
	JP	(HL)

; Cartridge cold boot entry (from 4002h): locate ROM slot, map page 2 into same slot, clear
; work RAM C000h-F0EFh, probe Konami companion cartridges, init V9938 SCREEN 5, install
; H.TIMI, and run main loop
CARTRIDGE_BOOT_INIT:
	DI
	LD	SP,GAME_STACK_TOP
	CALL	BIOS_RSLREG
	RRCA
	RRCA
	AND	03h
	LD	C,A
	LD	B,00h
	LD	HL,BIOS_EXPTBL
	ADD	HL,BC
	LD	A,(HL)
	AND	80h
	OR	C
	LD	C,A
	INC	HL
	INC	HL
	INC	HL
	INC	HL
	LD	A,(HL)
	AND	0Ch
	OR	C
	LD	H,80h
	CALL	BIOS_ENASLT
	LD	HL,SND_UNUSED_C000
	LD	DE,SND_UNUSED_C001
	LD	BC,30EFh
	LD	(HL),00h
	LDIR
	LD	A,03h
	LD	(CURRENT_PAGE3_BANK),A
	CALL	RESTORE_DEFAULT_CORE_BANKS
	IF	HINOTORI_ENHANCED
	CALL	HS_BOOT_INIT	; asm/enhanced/hscroll_core.asm
	ENDIF
	CALL	DETECT_SUPPORTED_COMPANION_CARTRIDGE
	LD	A,(COMPANION_CART_TYPE)
	CP	02h
	JR	Z,.loc_4117
	CALL	RESTORE_DEFAULT_CORE_BANKS
	CALL	INIT_VDP_SCREEN5_AND_SAT_SHADOWS
	DI
	LD	A,C3h
	LD	(BIOS_H_TIMI),A
	LD	HL,HTIMI_VBLANK_HANDLER
	LD	(BIOS_H_TIMI_ADDR),HL
	XOR	A
	LD	(BIOS_CLIKSW),A
	LD	(BOOT_DISPLAY_MODE_FLAG),A
	EI
	JR	$

.loc_4117:
	LD	A,01h
	LD	(BOOT_DISPLAY_MODE_FLAG),A
	LD	A,09h
	LD	(MAPPER_PAGE3),A
	JP	KING_KONG2_COMBINATION_INIT_ENTRY	; asm/banks/bank09.asm

; Companion-cartridge VBlank hotkey handler when COMPANION_CART_TYPE is non-zero
HANDLE_COMPANION_PAUSE_COMBO:
	LD	A,07h
	CALL	BIOS_SNSMAT
	CPL
	AND	10h
	LD	B,A
	LD	A,01h
	CALL	BIOS_SNSMAT
	CPL
	AND	80h
	OR	B
	LD	HL,COMBINATION_HOTKEY_BITS
	LD	C,(HL)
	LD	(HL),A
	XOR	C
	AND	(HL)
	LD	C,A
	LD	HL,COMBINATION_INPUT_STATE
	LD	A,(HL)
	OR	A
	JR	NZ,.loc_4150
	BIT	04h,C
	JP	Z,RUN_HTIMI_CORE_IRQ_BODY
	LD	(HL),C
	CALL	SAVE_PSG_CHANNEL_VOLUMES
	EI
	RET

.loc_4150:
	BIT	07h,C
	JP	NZ,.loc_415b
	BIT	04h,C
	JR	Z,.loc_4161
	XOR	A
	LD	(HL),A

.loc_415b:
	CALL	RESTORE_PSG_CHANNEL_VOLUMES
	JP	RUN_HTIMI_CORE_IRQ_BODY

.loc_4161:
	CALL	MUTE_ALL_PSG_CHANNELS
	EI
	RET

; Read and save current PSG R#8-R#10 volume registers into SAVED_PSG_VOL_A..C
SAVE_PSG_CHANNEL_VOLUMES:
	LD	A,08h
	CALL	BIOS_RDPSG
	LD	(SAVED_PSG_VOL_A),A
	LD	A,09h
	CALL	BIOS_RDPSG
	LD	(SAVED_PSG_VOL_B),A
	LD	A,0Ah
	CALL	BIOS_RDPSG
	LD	(SAVED_PSG_VOL_C),A

; Zero PSG R#8-R#10 channel volume registers via BIOS_WRTPSG
MUTE_ALL_PSG_CHANNELS:
	LD	E,00h
	LD	A,08h
	CALL	BIOS_WRTPSG
	LD	E,00h
	INC	A
	CALL	BIOS_WRTPSG
	LD	E,00h
	INC	A
	JP	BIOS_WRTPSG	; asm/core/constants.asm

; Restore PSG R#8-R#10 channel volume registers from SAVED_PSG_VOL_A..C
RESTORE_PSG_CHANNEL_VOLUMES:
	LD	A,(SAVED_PSG_VOL_A)
	LD	E,A
	LD	A,08h
	CALL	BIOS_WRTPSG
	LD	A,(SAVED_PSG_VOL_B)
	LD	E,A
	LD	A,09h
	CALL	BIOS_WRTPSG
	LD	A,(SAVED_PSG_VOL_C)
	LD	E,A
	LD	A,0Ah
	JP	BIOS_WRTPSG	; asm/core/constants.asm

; Queue sound command ID in A to Bank 14 driver unless MAIN_CONTROL_FLAGS bit 6 locks audio
QUEUE_SOUND_COMMAND_IF_UNLOCKED:
	DI
	PUSH	HL
	LD	HL,MAIN_CONTROL_FLAGS
	BIT	06h,(HL)
	JP	NZ,DISPATCH_SOUND_COMMAND_SAVING_BANKS
	LD	HL,SOUND_MUTE_TOGGLE_LATCH
	BIT	00h,(HL)
	JP	NZ,ABORT_SOUND_COMMAND_RESTORE_HL
	JP	DISPATCH_SOUND_COMMAND_SAVING_BANKS

; Save mapper pages 2-3, map Banks 14 and 15, invoke Bank 14 START_OR_QUEUE_SOUND, and
; restore mapper state
DISPATCH_SOUND_COMMAND:
	DI
	PUSH	HL

; Save page-2/page-3 mapper shadows, map banks 0Eh/0Fh, invoke START_OR_QUEUE_SOUND, and
; restore banks
DISPATCH_SOUND_COMMAND_SAVING_BANKS:
	PUSH	DE
	PUSH	BC
	PUSH	AF
	LD	C,A
	LD	A,(MAPPER_BANK_PAGE2)
	LD	(SAVED_MAPPER_PAGE2),A
	LD	A,(MAPPER_BANK_PAGE3)
	LD	(SAVED_MAPPER_PAGE3),A
	LD	A,0Eh
	LD	(MAPPER_PAGE2),A
	LD	(MAPPER_BANK_PAGE2),A
	LD	A,0Fh
	LD	(MAPPER_PAGE3),A
	LD	(MAPPER_BANK_PAGE3),A
	LD	A,C
	CALL	START_OR_QUEUE_SOUND
	DI
	LD	A,(SAVED_MAPPER_PAGE2)
	LD	(MAPPER_PAGE2),A
	LD	(MAPPER_BANK_PAGE2),A
	LD	A,(SAVED_MAPPER_PAGE3)
	LD	(MAPPER_PAGE3),A
	LD	(MAPPER_BANK_PAGE3),A
	POP	AF
	POP	BC
	POP	DE

; Restore HL, re-enable interrupts, and return when SFX is muted or locked out
ABORT_SOUND_COMMAND_RESTORE_HL:
	POP	HL
	EI
	RET

; Per-frame main loop body: wait for VBlank divider, poll joystick/keyboard inputs, and
; dispatch MAIN_STATE (00h-12h)
RUN_MAIN_STATE_FRAME:
	LD	HL,VBLANK_TICK_DIVIDER
	LD	A,(HL)
	CP	01h
	RET	Z
	LD	(HL),00h
	LD	A,03h
	LD	(CURRENT_PAGE3_BANK),A
	CALL	MAP_CORE_BANKS_01_02_03
	IF	HINOTORI_ENHANCED
	CALL	HS_STATE_GUARD	; asm/enhanced/hscroll_core.asm
	ENDIF
	LD	HL,MAIN_CONTROL_FLAGS
	BIT	00h,(HL)
	CALL	Z,POLL_JOYSTICK_AND_KEYBOARD_INPUT
	LD	HL,MAIN_CONTROL_FLAGS
	BIT	00h,(HL)
	CALL	NZ,POLL_ATTRACT_DEMO_INPUT_TICK
	LD	HL,MAIN_CONTROL_FLAGS
	BIT	00h,(HL)
	JR	Z,.loc_4235
	LD	A,(MAIN_STATE)
	CP	05h
	JR	NZ,.loc_4235
	LD	HL,0102h
	LD	(MAIN_STATE),HL

.loc_4235:
	LD	HL,GAME_TICK_COUNTER
	INC	(HL)
	LD	A,(SKIP_SUBSTATE_DISPATCH)
	OR	A
	JP	NZ,MAIN_STATE_DEFERRED_CB_HANDLER
	LD	BC,(MAIN_STATE)
	LD	A,C
	LD	HL,MAIN_CONTROL_FLAGS
	BIT	00h,(HL)
	JR	NZ,.loc_4250
	CP	03h
	JR	NC,.loc_4254

.loc_4250:
	LD	HL,POLL_STOP_PAUSE_AND_CHEAT_KEYS
	PUSH	HL

.loc_4254:
	CALL	INLINE_WORD_DISPATCH

; 19-entry inline DW dispatch table for MAIN_STATE (00h..12h)
MAIN_STATE_DISPATCH_TABLE:
	DW	MAIN_STATE_BOOT_LOGO_HANDLER	; [00h]
	DW	MAIN_STATE_TITLE_INIT_HANDLER	; [01h]
	DW	MAIN_STATE_TITLE_IDLE_HANDLER	; [02h]
	DW	MAIN_STATE_START_BLINK_HANDLER	; [03h]
	DW	MAIN_STATE_STAGE_INTRO_HANDLER	; [04h]
	DW	MAIN_STATE_GAMEPLAY_HANDLER	; [05h]
	DW	MAIN_STATE_PLAYER_DEATH_HANDLER	; [06h]
	DW	MAIN_STATE_GAME_OVER_HANDLER	; [07h]
	DW	MAIN_STATE_EXTRA_LIFE_HANDLER	; [08h]
	DW	MAIN_STATE_COMPANION_MENU_HANDLER	; [09h]
	DW	MAIN_STATE_PAUSE_PASSWORD_HANDLER	; [0Ah]
	DW	MAIN_STATE_DEFERRED_CB_HANDLER	; [0Bh]
	DW	MAIN_STATE_ENDING_DEMO_HANDLER	; [0Ch]
	DW	MAIN_STATE_POWER_UP_HANDLER	; [0Dh]
	DW	MAIN_STATE_HANDLER_0E	; [0Eh]
	DW	MAIN_STATE_HANDLER_0F	; [0Fh]
	DW	MAIN_STATE_NOOP_HANDLER	; [10h]
	DW	MAIN_STATE_ITEM_INFO_HANDLER	; [11h]
	DW	MAIN_STATE_BIRD_MESSAGE_HANDLER	; [12h]

; MainState 10h: unused no-op state
MAIN_STATE_NOOP_HANDLER:
	RET

; MainState 00h: Konami boot logo display and fade sequence
MAIN_STATE_BOOT_LOGO_HANDLER:
	DJNZ	.loc_4290
	CALL	DISABLE_VDP_SPRITES
	CALL	UPDATE_KONAMI_BOOT_LOGO_STATE
	LD	A,(DEFERRED_CALLBACK_PTR)
	OR	A
	RET	Z
	LD	A,68h
	JP	SET_STATE_TIMER_AND_NEXT_SUBSTATE

.loc_4290:
	DJNZ	.loc_429d
	LD	HL,MAIN_STATE_TIMER
	DEC	(HL)
	RET	NZ
	CALL	READ_CURRENT_V9938_PALETTE_FROM_VRAM
	JP	ADVANCE_MAIN_SUBSTATE

.loc_429d:
	DJNZ	.loc_42ac
	CALL	START_PALETTE_FADE_OUT_TO_BLACK
	CALL	START_PALETTE_FADE_OUT_TO_BLACK
	CALL	START_PALETTE_FADE_OUT_TO_BLACK
	RET	NZ
	JP	ADVANCE_MAIN_SUBSTATE

.loc_42ac:
	DJNZ	.loc_42b7
	CALL	CLEAR_TITLE_VRAM_AND_BLACK_PALETTE
	CALL	DRAW_TITLE_SCREEN_AND_COPYRIGHT
	JP	ADVANCE_MAIN_STATE

.loc_42b7:
	CALL	RESET_VERTICAL_SCROLL_TO_ZERO
	CALL	CLEAR_VRAM_AND_ENABLE_DISPLAY
	CALL	DRAW_KONAMI_BOOT_LOGO_SCREEN
	JP	ADVANCE_MAIN_SUBSTATE

; MainState 01h: Title Firebird phase transition countdown
MAIN_STATE_TITLE_INIT_HANDLER:
	DJNZ	.loc_42d5
	LD	A,(GAME_TICK_COUNTER)
	AND	07h
	RET	NZ
	LD	HL,MAIN_STATE_TIMER
	DEC	(HL)
	RET	NZ
	CALL	READ_CURRENT_V9938_PALETTE_FROM_VRAM
	JR	ADVANCE_MAIN_SUBSTATE

.loc_42d5:
	DJNZ	.loc_42de
	CALL	START_PALETTE_FADE_OUT_TO_BLACK
	RET	NZ
	JP	ADVANCE_MAIN_STATE

.loc_42de:
	CALL	START_TITLE_PALETTE_FADE_IN
	RET	NZ
	LD	A,61h
	CALL	DISPATCH_SOUND_COMMAND
	LD	A,1Ch
	JR	SET_STATE_TIMER_AND_NEXT_SUBSTATE

; MainState 02h: Title screen idle loop, SPACE/trigger start check, and attract-mode demo
; timer
MAIN_STATE_TITLE_IDLE_HANDLER:
	DJNZ	PREPARE_ATTRACT_DEMO_TRANSITION
	CALL	UPDATE_ATTRACT_DEMO_TIMER_AND_REPLAY
	LD	A,(GAME_ACTIVE_SESSION_FLAG)
	OR	A
	JR	Z,.loc_4323
	LD	A,(PRESSED_KEY_ROW6_BITS)
	RRA
	LD	B,0Ah
	JP	C,TRANSITION_TO_MAIN_STATE_B
	RRA
	LD	B,0Dh
	JP	C,TRANSITION_TO_MAIN_STATE_B
	RRA
	LD	B,11h
	JP	C,TRANSITION_TO_MAIN_STATE_B
	LD	HL,MAP_RELOAD_AND_PWD_FLAG
	BIT	07h,(HL)
	CALL	NZ,EXECUTE_PENDING_ROUTE_TRANSITION
	LD	A,(PRESSED_KEY_ROW7_BITS)
	LD	B,0Eh
	RRCA
	JP	C,TRANSITION_TO_MAIN_STATE_B
	LD	B,0Fh
	RRCA
	RET	NC
	JP	TRANSITION_TO_MAIN_STATE_B

.loc_4323:
	LD	A,74h
	LD	(SND_FADEOUT_TARGET_ID),A
	LD	HL,MAIN_CONTROL_FLAGS
	RES	00h,(HL)

; Load A = MAIN_STATE_GAMEPLAY (05h) and transition main state
SET_MAIN_STATE_GAMEPLAY:
	XOR	A

; Set MAIN_STATE = A, MAIN_STATE_TIMER = 20h, and zero MAIN_SUBSTATE
SET_MAIN_STATE_AND_RESET_SUBSTATE:
	LD	(MAIN_STATE),A
	LD	A,20h
	LD	(MAIN_STATE_TIMER),A
	JP	RESET_MAIN_SUBSTATE

; Clear VRAM, reset attract wait high counter, configure demo state, and set 32-frame
; transition timer
PREPARE_ATTRACT_DEMO_TRANSITION:
	CALL	CLEAR_VRAM_AND_ENABLE_DISPLAY
	XOR	A
	LD	(ATTRACT_WAIT_HIGH_CNT),A
	CALL	SETUP_NEXT_ATTRACT_DEMO_SESSION
	LD	A,20h

; Store A into MAIN_STATE_TIMER (C104h) and increment MAIN_SUBSTATE
SET_STATE_TIMER_AND_NEXT_SUBSTATE:
	LD	(MAIN_STATE_TIMER),A

; Increment MAIN_SUBSTATE (C101h)
ADVANCE_MAIN_SUBSTATE:
	LD	HL,MAIN_SUBSTATE
	INC	(HL)
	RET

; MainState 03h: blink 'PUSH SPACE KEY' prompt during start fanfare
MAIN_STATE_START_BLINK_HANDLER:
	DJNZ	.loc_4360
	LD	HL,MAIN_STATE_TIMER
	DEC	(HL)
	JR	Z,ADVANCE_MAIN_SUBSTATE
	BIT	01h,(HL)
	LD	HL,TITLE_PUSH_SPACE_KEY_TEXT
	JP	Z,DRAW_POSITIONED_TEXT_STRING
	JP	DRAW_TEXT_AT_DE

.loc_4360:
	DJNZ	.loc_4371
	CALL	BLANK_DISPLAY_AND_CLEAR_VRAM
	CALL	WAIT_FOR_VDP_COMMAND_COMPLETE
	CALL	INITIALIZE_NEW_GAME_STATE
	CALL	HANDLE_PENDING_CHEAT_STAGE_SELECT
	JP	ADVANCE_MAIN_STATE

.loc_4371:
	LD	A,74h
	CALL	QUEUE_SOUND_COMMAND_IF_UNLOCKED
	CALL	WAIT_FOR_VDP_COMMAND_COMPLETE
	LD	A,64h
	CALL	DISPATCH_SOUND_COMMAND
	LD	A,14h
	JP	SET_STATE_TIMER_AND_NEXT_SUBSTATE

; MainState 04h: Stage intro screen, level/route graphics setup, and transition to active
; play
MAIN_STATE_STAGE_INTRO_HANDLER:
	DJNZ	DECREMENT_BCD_LIVES_FOR_STAGE_START
	CALL	INITIALIZE_NEW_STAGE_ENTRY_SETUP
	LD	HL,GAME_ACTIVE_SESSION_FLAG
	LD	(HL),01h
	CALL	ENABLE_VDP_SPRITES

; Increment MAIN_STATE and clear MAIN_SUBSTATE
ADVANCE_MAIN_STATE:
	LD	A,20h
	LD	(MAIN_STATE_TIMER),A
	LD	HL,MAIN_STATE
	INC	(HL)

; Reset MAIN_SUBSTATE to 00h
RESET_MAIN_SUBSTATE:
	XOR	A
	LD	(MAIN_SUBSTATE),A
	RET

; Sync vertical scroll, subtract 1 from BCD lives on Stage Intro completion, blank display,
; and advance substate
DECREMENT_BCD_LIVES_FOR_STAGE_START:
	CALL	WRITE_VERTICAL_SCROLL_REGISTER
	LD	HL,PLAYER_LIVES_BCD
	LD	A,(HL)
	OR	A
	JR	Z,.loc_43ac
	ADD	A,99h
	DAA
	LD	(HL),A

.loc_43ac:
	CALL	DISABLE_VDP_DISPLAY_AND_SPRITES
	CALL	DISABLE_VDP_SPRITES
	JP	ADVANCE_MAIN_SUBSTATE

; MainState 05h: active gameplay frame, stage transition check, pause/subscreen hotkeys
; (F1-F5)
MAIN_STATE_GAMEPLAY_HANDLER:
	LD	HL,MAP_RELOAD_AND_PWD_FLAG
	BIT	07h,(HL)
	CALL	NZ,EXECUTE_PENDING_ROUTE_TRANSITION
	CALL	RUN_GAMEPLAY_FRAME
	LD	A,(GAME_ACTIVE_SESSION_FLAG)
	OR	A
	JP	Z,ADVANCE_MAIN_STATE
	LD	A,(GAO_MODE)
	CP	02h
	RET	Z
	LD	A,(PRESSED_KEY_ROW6_BITS)
	RRA
	LD	B,0Ah
	JR	C,TRANSITION_TO_MAIN_STATE_B
	RRA
	LD	B,0Dh
	JR	C,TRANSITION_TO_MAIN_STATE_B
	RRA
	LD	B,11h
	JR	C,TRANSITION_TO_MAIN_STATE_B
	LD	A,(PRESSED_KEY_ROW7_BITS)
	LD	B,0Eh
	RRCA
	JR	C,TRANSITION_TO_MAIN_STATE_B
	LD	B,0Fh
	RRCA
	JR	C,TRANSITION_TO_MAIN_STATE_B
	RET

; Set MAIN_STATE = B and reset substate/timer
TRANSITION_TO_MAIN_STATE_B:
	LD	A,B
	JP	SET_MAIN_STATE_AND_RESET_SUBSTATE
	IF	HINOTORI_ENHANCED = 00h

; Developer helper: reset route row to 001Fh, increment CURRENT_ROUTE_ID, and request stage
; reload
DEBUG_INCREMENT_ROUTE_ID:
	LD	HL,001Fh
	LD	(INITIAL_ROUTE_ROW),HL
	LD	HL,CURRENT_ROUTE_ID
	INC	(HL)
	LD	HL,MAP_RELOAD_AND_PWD_FLAG
	SET	07h,(HL)
	RET

; Developer helper: reset route row to 001Fh, decrement CURRENT_ROUTE_ID, and request stage
; reload
DEBUG_DECREMENT_ROUTE_ID:
	LD	HL,001Fh
	LD	(INITIAL_ROUTE_ROW),HL
	LD	HL,CURRENT_ROUTE_ID
	DEC	(HL)
	LD	HL,MAP_RELOAD_AND_PWD_FLAG
	SET	07h,(HL)
	RET
	ENDIF

; MainState 06h: handle Gao death, BCD life decrement (respecting CHEAT_INFINITE_LIVES), and
; Game Over vs retry
MAIN_STATE_PLAYER_DEATH_HANDLER:
	LD	HL,0000h
	LD	(CONTINUE_USED_WORD),HL
	LD	HL,PLAYER_LIVES_BCD
	LD	A,(CHEAT_INFINITE_LIVES)
	OR	A
	LD	A,(HL)
	JR	Z,.loc_4427
	ADD	A,01h
	DAA
	JR	Z,.loc_4427
	LD	(HL),A

.loc_4427:
	OR	A
	JR	NZ,ENTER_STAGE_INTRO_MAIN_STATE
	JR	QUEUE_GAME_OVER_MELODY_AND_ADVANCE

; Transition MAIN_STATE to 04h (Stage Intro card) and reset substate
ENTER_STAGE_INTRO_MAIN_STATE:
	LD	A,04h
	JP	SET_MAIN_STATE_AND_RESET_SUBSTATE

; Queue Sound ID 6Dh (Game Over melody) and advance MAIN_STATE to Game Over
QUEUE_GAME_OVER_MELODY_AND_ADVANCE:
	LD	A,6Dh
	CALL	QUEUE_SOUND_COMMAND_IF_UNLOCKED
	JP	ADVANCE_MAIN_STATE

; MainState 07h: Game Over melody wait and F5 Continue screen
MAIN_STATE_GAME_OVER_HANDLER:
	DJNZ	HANDLE_GAME_OVER_SUBSTATES
	LD	A,(PRESSED_KEY_ROW7_BITS)
	AND	02h
	JR	NZ,CONTINUE_FROM_GAME_OVER_RESET
	LD	A,(SND_CH0_SOUND_ID)
	OR	A
	RET	NZ

