; Clear temporary player buffs (Invisibility C858h, Invincible Aura C860h, Heart Orb base / cut
; standalone orb buff C87Ch [Item 0Ch], and Hourglass Time Stop C880h) and reset saved BGM
; channel locks (contains [a1] lock-clear bugfix at 80E4h). Clearing C87Ch here is the sole
; direct reference to Slot 11 in the ROM. This clear alone does not establish a working
; transient buff; that interpretation is speculative. The icon is reused for Heart Orbs.
RESET_TRANSIENT_GAO_AND_BGM_LOCKS:
	LD	A,(INV_TIME_STOP_TIMER)
	LD	B,A
	XOR	A
	LD	(INV_INVISIBILITY_TIMER),A
	LD	(INV_INVINCIBLE_AURA_TIMER),A
	IF	HINOTORI_ENHANCED = 00h
	LD	(INV_HEART_ORB_BASE_SLOT),A
	ENDIF
	LD	(INV_TIME_STOP_TIMER),A
	LD	A,B
	OR	A
	LD	A,00h
	IF	HINOTORI_A1 = 00h
	JR	NZ,.loc_80e9	; Original skips clearing SND_BGM_SAVED_LOCK when item active; [a1] always clears
	ENDIF
	LD	(SND_BGM_SAVED_LOCK),A

