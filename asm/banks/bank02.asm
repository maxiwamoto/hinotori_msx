; Offset terrain object IX Y by -30h and clear overlapping CPU sprite scanline colors within
; BC=(width, height)
MASK_SPRITE_COLORS_AT_TERRAIN_RECT:
	CALL	LOAD_OBJECT_XY_INTO_DE
	LD	A,E
	SUB	30h
	LD	E,A
	JP	MASK_ALL_CPU_SPRITE_COLORS_IN_RECT

; Load object IX screen coordinates into D=OBJ_X and E=OBJ_Y
LOAD_OBJECT_XY_INTO_DE:
	LD	D,(IX+OBJ_X)
	LD	E,(IX+OBJ_Y)
	RET

