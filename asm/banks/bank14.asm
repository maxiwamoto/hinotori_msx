START_OR_QUEUE_SOUND:
	LD	C,A
	LD	A,(SND_BGM_SAVED_LOCK)
	OR	A
	JR	NZ,CLASSIFY_SOUND_ID_CHANNEL_COUNT
	LD	A,C
	CP	70h
