; and 00h..CFh note/rest/macro trigger
DECODE_MUSIC_MODE_TRACK_COMMANDS:
	LD	A,(HL)
	AND	F0h
	CP	D0h
	LD	A,(HL)
	JP	NZ,CHECK_MUSIC_VOLUME_ENVELOPE_CMD
	AND	0Fh
	LD	(IX+SND_CH_TEMPO_UNIT),A
	INC	HL
	LD	A,(HL)

CHECK_MUSIC_VOLUME_ENVELOPE_CMD:
	CP	F0h
	JP	C,CHECK_MUSIC_EXTENDED_E_CMD
	AND	0Fh
	INC	A
	LD	(IX+SND_CH_INIT_VOLUME),A
	INC	HL
	LD	A,(HL)
	AND	F0h
	RRCA
	RRCA
	RRCA
	RRCA
	LD	(IX+SND_CH_ENV_ATTACK_TICKS),A
	LD	A,(HL)
	AND	0Fh
	LD	(IX+SND_CH_ENV_RELEASE_TICKS),A
	INC	HL
	LD	A,(HL)

CHECK_MUSIC_EXTENDED_E_CMD:
	CP	E0h
	JP	C,DECODE_MUSIC_NOTE_DURATION
	AND	0Fh
	CP	08h
	JP	C,HANDLE_MUSIC_OCTAVE_CMD
	JR	Z,HANDLE_MUSIC_DETUNE_E8_CMD
	CP	0Ch
	JP	Z,HANDLE_MUSIC_VIBRATO_EC_CMD
	CP	0Fh
	JP	Z,HANDLE_MUSIC_RESET_EF_CMD
	INC	HL
	LD	A,(HL)
	LD	(IX+SND_CH_MACRO_SET_ID),A
	JP	ADVANCE_TO_MUSIC_NOTE_BYTE

HANDLE_MUSIC_RESET_EF_CMD:
	XOR	A
	LD	(IX+SND_CH_MOD_FLAGS),A
	LD	(IX+SND_CH_MACRO_SET_ID),A
	INC	HL
	LD	A,(SND_BGM_MUTE_FLAG)
	OR	A
	JP	Z,DECODE_MUSIC_MODE_TRACK_COMMANDS
	XOR	A
	LD	(IX+SND_CH_MIXER_ENV_MODE),A
	LD	(IX+SND_CH_OUT_VOLUME),A
	PUSH	HL
	CALL	WRITE_CHANNEL_MIXER_AND_VOLUME_TO_PSG
	POP	HL
	JP	DECODE_MUSIC_MODE_TRACK_COMMANDS

HANDLE_MUSIC_VIBRATO_EC_CMD:
	SET	02h,(IX+SND_CH_MOD_FLAGS)
	INC	HL
	LD	A,(HL)
	LD	(IX+SND_CH_VIB_PARAM),A
	JP	ADVANCE_AND_LOOP_MUSIC_CMD

HANDLE_MUSIC_DETUNE_E8_CMD:
	SET	03h,(IX+SND_CH_MOD_FLAGS)

ADVANCE_AND_LOOP_MUSIC_CMD:
	INC	HL
	JP	DECODE_MUSIC_MODE_TRACK_COMMANDS

HANDLE_MUSIC_OCTAVE_CMD:
	LD	(IX+SND_CH_OCTAVE_SHIFT),A

ADVANCE_TO_MUSIC_NOTE_BYTE:
	INC	HL
	LD	A,(HL)

DECODE_MUSIC_NOTE_DURATION:
	AND	0Fh
	LD	B,A
	LD	A,(IX+SND_CH_TEMPO_UNIT)
	JR	Z,STORE_MUSIC_NOTE_DURATION

MULTIPLY_MUSIC_NOTE_DURATION_LOOP:
	ADD	A,(IX+SND_CH_TEMPO_UNIT)
	DJNZ	MULTIPLY_MUSIC_NOTE_DURATION_LOOP

STORE_MUSIC_NOTE_DURATION:
	LD	(IX+SND_CH_NOTE_DURATION),A
	LD	A,(HL)
	CALL	ADVANCE_AND_STORE_TRACK_POINTER
	AND	F0h
	RRCA
	RRCA
	RRCA
	RRCA
	LD	B,A
	LD	A,(IX+SND_CH_MACRO_SET_ID)
	OR	A
	JR	NZ,TRIGGER_MUSIC_MACRO_NOTE
	LD	A,B
	SUB	0Ch
	JP	Z,HANDLE_MUSIC_REST_NOTE
	LD	A,(IX+SND_CH_INIT_VOLUME)
	LD	(IX+SND_CH_ENV_VOLUME),A
	LD	(IX+SND_CH_OUT_VOLUME),A
	RES	00h,(IX+SND_CH_MOD_FLAGS)
	XOR	A
	LD	(IX+SND_CH_VIB_TIMER),A
	LD	(IX+SND_CH_VIB_POLARITY),A
	LD	E,(IX+SND_CH_NOTE_DURATION)
	LD	(IX+SND_CH_NOTE_TIMER),E
	LD	A,(SND_BGM_MUTE_FLAG)
	OR	A
	RET	NZ
	LD	A,(IX+SND_CH_ENV_ATTACK_TICKS)
	ADD	A,E
	LD	(IX+SND_CH_ENV_DECAY_CNT),A
	LD	A,B
	LD	HL,PSG_SEMITONE_BASE_PERIOD_TABLE
	ADD	A,L
	LD	L,A
	JR	NC,LOAD_BASE_SEMITONE_PERIOD
	INC	H

LOAD_BASE_SEMITONE_PERIOD:
	LD	L,(HL)
	LD	H,00h
	LD	A,(IX+SND_CH_OCTAVE_SHIFT)
	OR	A
	JR	Z,STORE_MUSIC_TONE_PERIOD
	LD	B,A

SHIFT_PERIOD_BY_OCTAVE_LOOP:
	ADD	HL,HL
	DJNZ	SHIFT_PERIOD_BY_OCTAVE_LOOP

STORE_MUSIC_TONE_PERIOD:
	LD	(IX+SND_CH_TONE_PERIOD_LO),L
	LD	(IX+SND_CH_TONE_PERIOD_HI),H
	CALL	WRITE_ARBITRATED_CHANNEL_TONE_PERIOD
	JP	WRITE_CHANNEL_MIXER_AND_VOLUME_TO_PSG

TRIGGER_MUSIC_MACRO_NOTE:
	ADD	A,A
	LD	DE,SOUND_MACRO_SET_PTR_TABLE - 02h
	ADD	A,E
	LD	E,A
	JR	NC,LOAD_MACRO_SUBTABLE_POINTER
	INC	D

LOAD_MACRO_SUBTABLE_POINTER:
	LD	A,(DE)
	LD	L,A
	INC	DE
	LD	A,(DE)
	LD	H,A
	LD	A,(IX+SND_CH_NOTE_DURATION)
	LD	(IX+SND_CH_NOTE_TIMER),A
	LD	A,(SND_BGM_MUTE_FLAG)
	OR	A
	RET	NZ
	LD	A,B
	ADD	A,A
	ADD	A,L
	LD	L,A
	JR	NC,LOAD_MACRO_MICRO_STREAM_POINTER
	INC	H

LOAD_MACRO_MICRO_STREAM_POINTER:
	LD	E,(HL)
	LD	(IX+SND_CH_MACRO_PTR_LO),E
	INC	HL
	LD	D,(HL)
	LD	(IX+SND_CH_MACRO_PTR_HI),D
	EX	DE,HL
	LD	A,(HL)
	JP	DECODE_RAW_PSG_OR_MACRO_STEP

; Ticks SND_CH_MACRO_TIMER for active percussion/instrument micro-streams, silences channel
; on micro-stream FFh end (9799h), and silences channel on MML rest notes C0h..CFh (97A3h)
UPDATE_MACRO_STREAM_AND_MUSIC_REST:
	DEC	(IX+SND_CH_MACRO_TIMER)
	RET	NZ
	LD	L,(IX+SND_CH_MACRO_PTR_LO)
	LD	H,(IX+SND_CH_MACRO_PTR_HI)
	LD	A,(HL)
	CP	FFh
	JR	Z,SILENCE_FINISHED_MACRO_NOTE
	JP	DECODE_RAW_PSG_OR_MACRO_STEP

ADVANCE_MACRO_STREAM_POINTER:
	INC	HL
	LD	(IX+SND_CH_MACRO_PTR_LO),L
	LD	(IX+SND_CH_MACRO_PTR_HI),H
	JP	STORE_RAW_TONE_PERIOD_AND_VOLUME

SILENCE_FINISHED_MACRO_NOTE:
	XOR	A
	LD	(IX+SND_CH_MIXER_ENV_MODE),A
	LD	(IX+SND_CH_OUT_VOLUME),A
	JP	WRITE_CHANNEL_MIXER_AND_VOLUME_TO_PSG

HANDLE_MUSIC_REST_NOTE:
	XOR	A
	LD	(IX+SND_CH_TONE_PERIOD_LO),A
	LD	(IX+SND_CH_TONE_PERIOD_HI),A
	LD	(IX+SND_CH_OUT_VOLUME),A
	LD	A,(IX+SND_CH_NOTE_DURATION)
	LD	(IX+SND_CH_NOTE_TIMER),A
	CALL	WRITE_ARBITRATED_CHANNEL_TONE_PERIOD
	JP	WRITE_CHANNEL_MIXER_AND_VOLUME_TO_PSG

; Handles FFh track terminator: pops 1-level subroutine return address from SND_CH_RET_PTR
; if non-zero, else deactivates channel and (when C=7 Ch3 SFX finishes) restores BGM Ch2
; (C050h) pitch and mixer/volume to PSG Ch C
HANDLE_TRACK_END_OR_SUBROUTINE_RETURN:
	LD	A,(IX+SND_CH_RET_PTR_HI)
	OR	A
	JP	Z,TERMINATE_SOUND_CHANNEL
	LD	(IX+SND_CH_TRACK_PTR_HI),A
	LD	A,(IX+SND_CH_RET_PTR_LO)
	LD	(IX+SND_CH_TRACK_PTR_LO),A
	LD	(IX+SND_CH_RET_PTR_HI),00h
	LD	(IX+SND_CH_NOTE_TIMER),01h
	JP	UPDATE_ACTIVE_SOUND_CHANNEL

TERMINATE_SOUND_CHANNEL:
	XOR	A
	LD	(IX+SND_CH_SOUND_ID),A
	LD	(IX+SND_CH_MIXER_ENV_MODE),A
	LD	(IX+SND_CH_LOOP_COUNTER),A
	LD	(IX+SND_CH_MACRO_SET_ID),A
	LD	(IX+SND_CH_TONE_PERIOD_LO),A
	LD	(IX+SND_CH_TONE_PERIOD_HI),A
	LD	(IX+SND_CH_OUT_VOLUME),A
	LD	(IX+SND_CH_VIB_POLARITY),A
	LD	A,C
	CP	07h
	JP	C,WRITE_CHANNEL_MIXER_AND_VOLUME_TO_PSG

RESTORE_BGM_CHANNEL2_AFTER_SFX:
	DEC	C
	DEC	C
	LD	IX,SND_CH2_REC
	LD	(IX+SND_CH_OUT_VOLUME),08h
	CALL	WRITE_TONE_PERIOD_REGISTERS
	JP	WRITE_MIXER_AND_VOLUME_REGISTERS

; Refreshes PSG registers on BGM restore (9803h), arbitrates PSG Ch C ownership between Ch2
; BGM and Ch3 SFX (980Eh), applies optional +1 detune, and writes 12-bit tone period to PSG
; R#0..R#5 via BIOS WRTPSG (0093h)
WRITE_CHANNEL_TONE_PERIOD_TO_PSG:
	LD	A,(SND_FORCE_PSG_REFRESH)
	OR	A
	RET	Z
	CALL	WRITE_ARBITRATED_CHANNEL_TONE_PERIOD
	JP	WRITE_CHANNEL_MIXER_AND_VOLUME_TO_PSG

WRITE_ARBITRATED_CHANNEL_TONE_PERIOD:
	LD	A,(SND_CH3_SOUND_ID)
	LD	E,A
	LD	A,C
	CP	05h
	JP	C,WRITE_TONE_PERIOD_REGISTERS
	JP	NZ,WRITE_SFX_OVERLAY_TONE_PERIOD
	LD	A,E
	OR	A
	RET	NZ
	JP	WRITE_TONE_PERIOD_REGISTERS

WRITE_SFX_OVERLAY_TONE_PERIOD:
	LD	A,E
	OR	A
	RET	Z
	DEC	C
	DEC	C
	CALL	WRITE_TONE_PERIOD_REGISTERS
	INC	C
	INC	C
	RET

WRITE_TONE_PERIOD_REGISTERS:
	LD	L,(IX+SND_CH_TONE_PERIOD_LO)
	LD	H,(IX+SND_CH_TONE_PERIOD_HI)
	BIT	03h,(IX+SND_CH_MOD_FLAGS)
	JP	Z,WRITE_COARSE_AND_FINE_TONE_REGISTERS
	INC	HL

WRITE_COARSE_AND_FINE_TONE_REGISTERS:
	LD	A,C
	LD	E,H
	CALL	BIOS_WRTPSG
	LD	A,C
	DEC	A
	LD	E,L
	CALL	BIOS_WRTPSG
	LD	A,(IX+SND_CH_MACRO_SET_ID)
	OR	A
	RET	NZ
	LD	A,(IX+SND_CH_MUSIC_MODE)
	OR	A
	RET	Z
	LD	(IX+SND_CH_MIXER_ENV_MODE),02h
	RET

; 12 single-byte PSG base tone periods (6Bh..39h = 107..57) for highest-octave semitones
; C..B; shifted left SND_CH_OCTAVE_SHIFT times for octaves 0..7
PSG_SEMITONE_BASE_PERIOD_TABLE:
	DB	6Bh,65h,5Fh,5Ah,55h,50h,4Ch,47h,43h,40h,3Ch,39h

; Increments SND_FADEOUT_FRAME_CNT (C0F5h, 16 VBlanks/step) and SND_FADEOUT_ATTEN (C0F6h,
; 0..9); after 144 frames clears C0F4h..C0F6h and dispatches queued Sound ID via jp
; StartOrQueueSound (9400h)
UPDATE_MASTER_BGM_FADEOUT:
	LD	HL,SND_FADEOUT_FRAME_CNT
	INC	(HL)
	LD	A,(HL)
	CP	10h
	RET	C
	LD	(HL),00h
	INC	HL
	INC	(HL)
	LD	A,(HL)
	CP	09h
	RET	C
	XOR	A
	LD	HL,SND_FADEOUT_TARGET_ID
	LD	E,(HL)
	LD	(HL),A
	INC	L
	LD	(HL),A
	INC	L
	LD	(HL),A
	LD	A,E
	JP	START_OR_QUEUE_SOUND

; Arbitrates PSG Ch C between Ch2 BGM and Ch3 SFX, updates PSG R#7 mixer bits, subtracts
; SND_FADEOUT_ATTEN on music channels, writes PSG R#13 envelope shape if enabled, and writes
; volume to PSG R#8..R#10
WRITE_CHANNEL_MIXER_AND_VOLUME_TO_PSG:
	LD	A,(SND_CH3_SOUND_ID)
	LD	E,A
	LD	A,C
	CP	05h
	JP	C,WRITE_MIXER_AND_VOLUME_REGISTERS
	JP	NZ,WRITE_SFX_OVERLAY_MIXER_AND_VOLUME
	LD	A,E
	OR	A
	RET	NZ
	JP	WRITE_MIXER_AND_VOLUME_REGISTERS

WRITE_SFX_OVERLAY_MIXER_AND_VOLUME:
	LD	A,E
	OR	A
	RET	Z
	DEC	C
	DEC	C

WRITE_MIXER_AND_VOLUME_REGISTERS:
	CALL	UPDATE_CHANNEL_PSG_MIXER_BITS
	LD	A,C
	RRCA
	ADD	A,88h
	LD	D,A
	LD	H,(IX+SND_CH_OUT_VOLUME)
	LD	A,(IX+SND_CH_MUSIC_MODE)
	OR	A
	JR	Z,CHECK_HARDWARE_ENVELOPE_SHAPE_WRITE
	LD	A,(SND_FADEOUT_ATTEN)
	OR	A
	JP	Z,CHECK_HARDWARE_ENVELOPE_SHAPE_WRITE
	LD	E,A
	LD	A,H
	SUB	E
	RET	M
	BIT	03h,(IX+SND_CH_MIXER_ENV_MODE)
	RET	NZ
	LD	H,A

CHECK_HARDWARE_ENVELOPE_SHAPE_WRITE:
	LD	A,(IX+SND_CH_MIXER_ENV_MODE)
	BIT	03h,A
	JP	Z,WRITE_CHANNEL_AMPLITUDE_REGISTER
	BIT	02h,A
	RET	NZ
	LD	E,H
	LD	A,0Dh
	CALL	BIOS_WRTPSG
	LD	A,10h
	LD	H,A

WRITE_CHANNEL_AMPLITUDE_REGISTER:
	LD	A,D
	LD	E,H
	JP	BIOS_WRTPSG	; asm/core/constants.asm

; Copies 0060h bytes (3 x $20B channel structs) between active BGM (C010h..C06Fh) and saved
; BGM (C090h..C0EFh), moves A to C, and clears SND_BGM_RESTORE_REQ (C0F1h)
COPY_THREE_SOUND_CHANNEL_RECORDS:
	LD	BC,0060h
	LDIR
	LD	C,A
	XOR	A
	LD	(SND_BGM_RESTORE_REQ),A
	RET

; Decodes FEh track control opcodes: FE 00 (toggle SND_CH_MUSIC_MODE 1<->0), FE FF <addr>
; (call 1-level track subroutine), and FE <count> <addr> (counted loop 01h..81h or infinite
; loop 82h..FEh)
HANDLE_TRACK_CONTROL_PREFIX_FE:
	INC	HL
	LD	A,(HL)
	OR	A
	JR	Z,TOGGLE_CHANNEL_MUSIC_MODE
	INC	A
	JR	Z,CALL_TRACK_SUBROUTINE
	LD	A,(IX+SND_CH_LOOP_COUNTER)
	INC	A
	CP	(HL)
	JR	Z,EXIT_TRACK_COUNTED_LOOP
	JP	M,TAKE_TRACK_LOOP_JUMP
	DEC	A

TAKE_TRACK_LOOP_JUMP:
	LD	(IX+SND_CH_LOOP_COUNTER),A
	INC	HL
	LD	A,(HL)
	LD	(IX+SND_CH_TRACK_PTR_LO),A
	INC	HL
	LD	A,(HL)
	LD	(IX+SND_CH_TRACK_PTR_HI),A
	JP	TRIGGER_IMMEDIATE_NEXT_FETCH

EXIT_TRACK_COUNTED_LOOP:
	INC	HL
	INC	HL
	XOR	A
	LD	(IX+SND_CH_LOOP_COUNTER),A

ADVANCE_PAST_CONTROL_SUBCMD:
	CALL	ADVANCE_AND_STORE_TRACK_POINTER

TRIGGER_IMMEDIATE_NEXT_FETCH:
	INC	(IX+SND_CH_NOTE_TIMER)
	JP	UPDATE_ACTIVE_SOUND_CHANNEL

TOGGLE_CHANNEL_MUSIC_MODE:
	LD	A,(IX+SND_CH_MUSIC_MODE)
	OR	A
	JR	Z,ENABLE_CHANNEL_MUSIC_MODE
	DEC	(IX+SND_CH_MUSIC_MODE)
	JP	ADVANCE_PAST_CONTROL_SUBCMD

ENABLE_CHANNEL_MUSIC_MODE:
	INC	(IX+SND_CH_MUSIC_MODE)
	JP	ADVANCE_PAST_CONTROL_SUBCMD

CALL_TRACK_SUBROUTINE:
	INC	HL
	LD	E,(HL)
	LD	(IX+SND_CH_TRACK_PTR_LO),E
	INC	HL
	LD	D,(HL)
	LD	(IX+SND_CH_TRACK_PTR_HI),D
	INC	HL
	LD	(IX+SND_CH_RET_PTR_LO),L
	LD	(IX+SND_CH_RET_PTR_HI),H
	EX	DE,HL
	JP	DISPATCH_TRACK_BYTE_BY_MODE

; Increments HL by 1 and stores updated track cursor into SND_CH_TRACK_PTR (IX+03h..04h)
ADVANCE_AND_STORE_TRACK_POINTER:
	INC	HL
	LD	(IX+SND_CH_TRACK_PTR_LO),L
	LD	(IX+SND_CH_TRACK_PTR_HI),H
	RET

; Updates tone and noise enable bits for channel C (1, 3, 5) in SND_PSG_MIXER_SHADOW (C0F0h)
; from SND_CH_MIXER_ENV_MODE (IX+05h bits 1..0) and falls through to WritePsgMixerRegister
UPDATE_CHANNEL_PSG_MIXER_BITS:
	LD	A,(SND_PSG_MIXER_SHADOW)
	LD	E,A
	LD	A,(IX+SND_CH_MIXER_ENV_MODE)
	AND	03h
	LD	D,A
	LD	A,C
	CP	01h
	JR	Z,APPLY_TONE_AND_NOISE_MIXER_MASKS
	DEC	A

APPLY_TONE_AND_NOISE_MIXER_MASKS:
	LD	B,A
	BIT	01h,D
	CALL	Z,SET_PSG_MIXER_BITS
	BIT	01h,D
	CALL	NZ,CLEAR_PSG_MIXER_BITS
	LD	A,B
	RLCA
	RLCA
	RLCA
	BIT	00h,D
	CALL	Z,SET_PSG_MIXER_BITS
	BIT	00h,D
	CALL	NZ,CLEAR_PSG_MIXER_BITS

; Stores A to SND_PSG_MIXER_SHADOW (C0F0h) and writes PSG R#7 through BIOS WRTPSG (0093h),
; plus bitmask helpers ClearPsgMixerBits (996Fh) and SetPsgMixerBits (9973h)
WRITE_PSG_MIXER_REGISTER:
	LD	(SND_PSG_MIXER_SHADOW),A
	LD	E,A
	LD	A,07h
	JP	BIOS_WRTPSG	; asm/core/constants.asm

CLEAR_PSG_MIXER_BITS:
	CPL
	AND	E
	LD	E,A
	RET

SET_PSG_MIXER_BITS:
	OR	E
	LD	E,A
	RET

