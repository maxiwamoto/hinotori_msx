	LD	A,(IX+SND_CH_ENV_VOLUME)
	DEC	A
	JP	M,WRITE_CHANNEL_TONE_PERIOD_TO_PSG
	LD	(IX+SND_CH_ENV_VOLUME),A
	LD	(IX+SND_CH_OUT_VOLUME),A
	JP	WRITE_CHANNEL_MIXER_AND_VOLUME_TO_PSG

; MML vibrato pitch modulator: waits 10 frames before setting bit 0 of SND_CH_MOD_FLAGS,
; then toggles SND_CH_VIB_POLARITY every (SND_CH_VIB_PARAM>>4) frames to add/subtract
; (SND_CH_VIB_PARAM&0Fh) on SND_CH_TONE_PERIOD
UPDATE_CHANNEL_VIBRATO:
	BIT	00h,(IX+SND_CH_MOD_FLAGS)
	JP	NZ,RUN_ACTIVE_VIBRATO_OSCILLATION
	LD	A,(IX+SND_CH_VIB_TIMER)
	INC	A
	CP	0Ah
	JP	C,STORE_VIBRATO_TIMER
	INC	(IX+SND_CH_MOD_FLAGS)
	XOR	A
	JP	STORE_VIBRATO_TIMER

RUN_ACTIVE_VIBRATO_OSCILLATION:
	LD	A,(IX+SND_CH_VIB_PARAM)
	AND	F0h
	RRCA
	RRCA
	RRCA
	RRCA
	LD	E,A
	LD	A,(IX+SND_CH_VIB_TIMER)
	INC	A
	CP	E
	JP	C,STORE_VIBRATO_TIMER
	LD	E,(IX+SND_CH_TONE_PERIOD_LO)
	LD	D,(IX+SND_CH_TONE_PERIOD_HI)
	LD	A,(IX+SND_CH_VIB_PARAM)
	AND	0Fh
	LD	B,A
	LD	A,(IX+SND_CH_VIB_POLARITY)
	CPL
	LD	(IX+SND_CH_VIB_POLARITY),A
	AND	A
	LD	A,E
	JP	NZ,SUBTRACT_VIBRATO_DEPTH
	ADD	A,B
	LD	E,A
	JP	NC,STORE_MODULATED_TONE_PERIOD
	INC	D
	JP	STORE_MODULATED_TONE_PERIOD

SUBTRACT_VIBRATO_DEPTH:
	SUB	B
	LD	E,A
	JP	NC,STORE_MODULATED_TONE_PERIOD
	DEC	D

STORE_MODULATED_TONE_PERIOD:
	LD	(IX+SND_CH_TONE_PERIOD_LO),E
	LD	(IX+SND_CH_TONE_PERIOD_HI),D
	CALL	WRITE_ARBITRATED_CHANNEL_TONE_PERIOD
	XOR	A

STORE_VIBRATO_TIMER:
	LD	(IX+SND_CH_VIB_TIMER),A
	RET

