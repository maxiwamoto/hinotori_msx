; MML music-mode sustain tick: decrements SND_CH_NOTE_TIMER, dispatches active percussion
; micro-stream sustain (977Dh), or runs vibrato (95FDh) and software ADSR volume decay
UPDATE_MUSIC_CHANNEL_SUSTAIN:
	DEC	(IX+SND_CH_NOTE_TIMER)
	JP	Z,FETCH_NEXT_TRACK_BYTE
	LD	A,(SND_BGM_MUTE_FLAG)
	OR	A
	RET	NZ
	LD	A,(IX+SND_CH_MACRO_SET_ID)
	OR	A
	JP	NZ,UPDATE_MACRO_STREAM_AND_MUSIC_REST
	BIT	02h,(IX+SND_CH_MOD_FLAGS)
	CALL	NZ,UPDATE_CHANNEL_VIBRATO
	DEC	(IX+SND_CH_ENV_DECAY_CNT)
	LD	A,(IX+SND_CH_ENV_DECAY_CNT)
	CP	(IX+SND_CH_NOTE_TIMER)
	JP	NZ,DOUBLE_DECREMENT_ATTACK_DECAY_COUNTER
	LD	E,A
	LD	A,(IX+SND_CH_ENV_RELEASE_TICKS)
	CP	E
	JP	NC,APPLY_SOFTWARE_ENVELOPE_DECAY_STEP
	JP	WRITE_CHANNEL_TONE_PERIOD_TO_PSG

DOUBLE_DECREMENT_ATTACK_DECAY_COUNTER:
	DEC	(IX+SND_CH_ENV_DECAY_CNT)

