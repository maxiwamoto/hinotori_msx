; Check PASSWORD_INPUT_BUFFER against the 16 English CRC-16 secret password hashes
CHECK_ENGLISH_SECRET_PASSWORDS:
	LD	HL,PASSWORD_INPUT_BUFFER
	LD	DE,FFFFh

.crc_next_byte:
	LD	A,(HL)
	OR	A
	JR	Z,.crc_done
	INC	A
	JR	Z,.crc_done
	DEC	A
	INC	HL
	XOR	D
	LD	D,A
	LD	B,08h

.crc_bit_loop:
	SLA	E
	RL	D
	JR	NC,.crc_no_poly
	LD	A,D
	XOR	10h
	LD	D,A
	LD	A,E
	XOR	21h
	LD	E,A

.crc_no_poly:
	DJNZ	.crc_bit_loop
	JR	.crc_next_byte

.crc_done:
	LD	HL,SECRET_PASSWORD_EN_CRC16_TABLE
	LD	B,10h

.search_loop:
	LD	A,(HL)
	INC	HL
	CP	E
	LD	A,(HL)
	INC	HL
	JR	NZ,.search_next
	CP	D
	JR	Z,.matched_crc

.search_next:
	INC	HL
	INC	HL
	DJNZ	.search_loop
	RET

