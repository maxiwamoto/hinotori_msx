	LD	D,(HL)
	LD	HL,PASSWORD_DECODE_WORK_BUF
	LD	A,B
	CALL	ADD_A_TO_HL
	LD	A,(HL)
	OR	A
	RET	NZ
	INC	A
	LD	(SECRET_PWD_APPLIED_FLAG),A
	LD	(HL),A
	EX	DE,HL
	RET

